package config

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
)

// List of standard Java executable binaries to shim in ~/.jvm/bin
var standardJavaBinaries = []string{
	"java",
	"javac",
	"javap",
	"jar",
	"jshell",
	"jps",
	"jstack",
	"jmap",
	"keytool",
}

// EnsureShims creates lightweight proxy wrapper scripts in ~/.jvm/bin
// so non-interactive scripts, subshells, cron jobs, and background workers
// can invoke `java` or `javac` without needing interactive shell sourcing.
func EnsureShims(cfg *Config) error {
	binDir := filepath.Join(cfg.RootDir, "bin")
	if err := os.MkdirAll(binDir, 0755); err != nil {
		return err
	}

	for _, toolName := range standardJavaBinaries {
		if runtime.GOOS == "windows" {
			// Windows CMD shim (.cmd)
			cmdShimPath := filepath.Join(binDir, toolName+".cmd")
			cmdContent := fmt.Sprintf(`@echo off
REM Shim generated by jvm for %s
setlocal
set "JVM_DIR=%%~dp0.."
set "TARGET_DIR="

REM Check current.path fallback
if exist "%%JVM_DIR%%\current.path" (
    set /p TARGET_DIR=<"%%JVM_DIR%%\current.path"
)
if "%%TARGET_DIR%%"=="" (
    set "TARGET_DIR=%%JVM_DIR%%\current"
)

if exist "%%TARGET_DIR%%\bin\%s.exe" (
    "%%TARGET_DIR%%\bin\%s.exe" %%*
    exit /b %%ERRORLEVEL%%
)

echo jvm: %s not found in active Java installation. >&2
exit /b 1
`, toolName, toolName, toolName, toolName)
			_ = os.WriteFile(cmdShimPath, []byte(cmdContent), 0755)

			// Windows PowerShell shim (.ps1)
			ps1ShimPath := filepath.Join(binDir, toolName+".ps1")
			ps1Content := fmt.Sprintf(`$jvmDir = Split-Path -Parent $PSScriptRoot
$targetDir = "$jvmDir\current"
if (Test-Path "$jvmDir\current.path") {
    $targetDir = (Get-Content "$jvmDir\current.path" -Raw).Trim()
}
$exe = "$targetDir\bin\%s.exe"
if (Test-Path $exe) {
    & $exe @args
    exit $LASTEXITCODE
} else {
    Write-Error "jvm: %s not found in active Java installation."
    exit 1
}
`, toolName, toolName)
			_ = os.WriteFile(ps1ShimPath, []byte(ps1Content), 0755)
		} else {
			// POSIX shell shim
			shimPath := filepath.Join(binDir, toolName)
			shimContent := fmt.Sprintf(`#!/usr/bin/env bash
# Shim generated by jvm for %[1]s
JVM_DIR="${JVM_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
TARGET_DIR=""

# Check symlink or junction
if [ -d "$JVM_DIR/current" ]; then
    TARGET_DIR="$JVM_DIR/current"
elif [ -f "$JVM_DIR/current.path" ]; then
    TARGET_DIR="$(cat "$JVM_DIR/current.path")"
fi

if [ -n "$TARGET_DIR" ] && [ -x "$TARGET_DIR/bin/%[1]s" ]; then
    export JAVA_HOME="$TARGET_DIR"
    exec "$TARGET_DIR/bin/%[1]s" "$@"
fi

echo "jvm: %[1]s not found in active Java installation." >&2
exit 1
`, toolName)
			_ = os.WriteFile(shimPath, []byte(shimContent), 0755)
		}
	}
	return nil
}
